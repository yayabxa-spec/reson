const OVERRIDES_KEY = "wc_prompt_overrides_v1";

let cache: Partial<Record<PromptModuleKey, string>> = {};
let loadPromise: Promise<void> | null = null;

function loadOverrides(): Promise<void> {
  if (!loadPromise) {
    loadPromise = AsyncStorage.getItem(OVERRIDES_KEY)
      .then((raw) => {
        cache = {};
        if (raw) {
          try {
            const obj = JSON.parse(raw);
            if (obj && typeof obj === "object") {
              for (const [k, v] of Object.entries(obj)) {
                if (typeof v === "string") (cache as any)[k] = v;
              }
            }
          } catch {}
        }
      })
      .catch(() => {});
  }
  return loadPromise;
}

/** 取某模块生效的提示词：有非空覆盖用覆盖，否则用 fallback（默认模板） */
export async function resolvePrompt(
  key: PromptModuleKey,
  fallback?: string
): Promise<string> {
  await loadOverrides();
  const v = cache[key];
  if (v != null && v.trim()) return v;
  return fallback ?? PROMPT_DEFAULTS[key];
}

export async function getPromptOverrides(): Promise<
  Partial<Record<PromptModuleKey, string>>
> {
  await loadOverrides();
  return { ...cache };
}

export async function savePromptOverride(
  key: PromptModuleKey,
  text: string
): Promise<void> {
  await loadOverrides();
  const t = (text ?? "").trim();
  if (t) cache[key] = t;
  else delete cache[key];
  await AsyncStorage.setItem(OVERRIDES_KEY, JSON.stringify(cache));
}

export async function resetPromptOverride(
  key: PromptModuleKey
): Promise<void> {
  await loadOverrides();
  delete cache[key];
  await AsyncStorage.setItem(OVERRIDES_KEY, JSON.stringify(cache));
}

export async function resetAllPromptOverrides(): Promise<void> {
  cache = {};
  await AsyncStorage.removeItem(OVERRIDES_KEY);
}

/** 用真实数据填充模板里的 {{占位符}}（未提供的占位符原样保留） */
export function fillTemplate(
  tpl: string,
  vars: Record<string, string>
): string {
  let out = tpl;
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{{${k}}}`).join(v ?? "");
  }
  return out;
}
